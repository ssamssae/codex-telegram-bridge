def normalize_language(value: object) -> str:
    code = re.split(r'[-_.]', str(value or '').strip().lower(), maxsplit=1)[0]
    return code if code in SUPPORTED_LANGUAGES else ''


def translate(source: str, locale: str = 'en', **values: object) -> str:
    # Empty locale preserves legacy wording for objects made without a locale.
    translations = MESSAGES.get(source)
    text = translations.get(normalize_language(locale) or 'en', source) if translations and locale else source
    return text.format(**values) if values else text


class Language:
    """One allowlisted chat's language, independent of engine session state."""
    def __init__(self, state_dir: Path | None = None, *, default: str = 'en',
                 env_prefix: str = 'CRB', state_name: str = 'bridge-language.json') -> None:
        self.path = Path(state_dir) / state_name if state_dir is not None else None
        self.lock = threading.RLock()
        requested = os.environ.get(env_prefix + '_LANGUAGE') or os.environ.get('TAB_LANGUAGE')
        self.code = normalize_language(requested) or normalize_language(default) or 'en'
        if self.path is not None:
            try:
                saved = json.loads(self.path.read_text(encoding='utf-8'))
                if isinstance(saved, dict):
                    self.code = normalize_language(saved.get('language')) or self.code
            except (OSError, ValueError):
                pass

    def text(self, source: str, **values: object) -> str:
        return translate(source, self.code, **values)

    def command(self, text: str) -> str | None:
        tokens = text.strip().split()
        if not tokens or not re.fullmatch(r'/language(?:@[a-z0-9_]+)?', tokens[0], re.I):
            return None
        with self.lock:
            if len(tokens) == 1:
                return self.text('Language: {language}\nUse /language en or /language ko.', language=SUPPORTED_LANGUAGES[self.code])
            if len(tokens) != 2 or tokens[1].lower() not in SUPPORTED_LANGUAGES:
                return self.text('Supported languages: /language en, /language ko.')
            code = tokens[1].lower()
            try:
                if self.path is not None:
                    self.path.parent.mkdir(parents=True, exist_ok=True)
                    fd, name = tempfile.mkstemp(prefix='.bridge-language-', dir=self.path.parent)
                    try:
                        with os.fdopen(fd, 'w', encoding='utf-8') as out:
                            json.dump({'language': code}, out)
                            out.write('\n')
                            out.flush()
                            os.fsync(out.fileno())
                        os.replace(name, self.path)
                    finally:
                        if os.path.exists(name):
                            os.unlink(name)
            except OSError:
                return self.text('Could not save the language. Your previous setting is unchanged.')
            self.code = code
            return self.text('language_changed')

